 id uuid primary key default gen_random_uuid(),
 source_key text unique,
 site_name text not null check (length(trim(site_name)) between 1 and 100),
 staff_code text not null check (staff_code in ('한','찬','영')),
 start_date date not null,
 end_date date not null check (end_date >= start_date),
 event_type text not null check (length(trim(event_type)) between 1 and 50),
 contract_count integer check (contract_count >= 0),
 contract_amount bigint check (contract_amount between 0 and 9007199254740991),
 created_at timestamptz not null default now()
);
create index if not exists team_events_start_staff_idx on public.team_events(start_date,staff_code);
alter table public.team_events enable row level security;
drop policy if exists team_events_shared_access on public.team_events;
create policy team_events_shared_access on public.team_events for all to anon, authenticated using (true) with check (true);
grant select, insert, update, delete on public.team_events to anon, authenticated, service_role;
